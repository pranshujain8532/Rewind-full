import { test } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import { captureSession, createRecord, expect, startJob } from './helpers';
import { recoverHarnessWorker, stopHarnessWorker } from './worker';
const artifacts = process.env.REWIND_BROWSER_ARTIFACT_DIR!;
test.setTimeout(180000);
let recovered: number | undefined;
test.beforeAll(() => { recovered = recoverHarnessWorker('p5'); });
test.afterAll(() => stopHarnessWorker(recovered));
for (const width of [1440, 1280, 390]) {
  test(`signed bundle and original-attack regression at ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: width === 390 ? 844 : width === 1440 ? 900 : 720 });
    await captureSession(page); await startJob(page); const record = await createRecord(page);
    await expect(page.getByText(/Governance mapping pending/)).toBeVisible();
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('link', { name: 'Download signed evidence bundle', exact: true }).click();
    const destination = path.join(artifacts, `p5-evidence-${width}.json`);
    await (await downloadEvent).saveAs(destination);
    const bundle = JSON.parse(fs.readFileSync(destination, 'utf8'));
    expect(bundle.format).toBe('rewind-evidence-v1'); expect(bundle.report.mode).toBe('simulated');
    expect(bundle.report.governance_mapping.entries).toEqual([]);
    const publicKey = fs.readFileSync(path.join(artifacts, 'data/keys/trusted-public.ed25519')).toString('hex');
    await page.getByLabel('Trusted public key (64 hexadecimal characters)').fill(publicKey);
    await page.getByRole('button', { name: 'Verify bundle', exact: true }).click();
    await expect(page.locator('.verification-result')).toContainText('Integrity verified under supplied key');
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path: path.join(artifacts, `p5-evidence-page-${width}.png`), fullPage: true });
    await page.getByRole('link', { name: 'Create regression', exact: true }).click();
    const firstResponse = page.waitForResponse(r => r.url().endsWith('/api/regression-runs') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Run original-attack regression' }).click();
    const firstRun = await (await firstResponse).json();
    await expect(page.locator('[data-regression-id]')).toHaveAttribute('data-regression-id', firstRun.id);
    await expect(page.getByRole('heading', { name: 'Regression: completed · pass' })).toBeVisible();
    const result = await (await page.request.get(`/api/regression-runs/${firstRun.id}`)).json();
    expect(result.manifest.arms.vulnerable.status).toBe('fail');
    expect(result.manifest.arms.fixed.harmful_attempts).toBe(0);
    expect(result.manifest.arms.fixed.task_success).toBeTruthy(); expect(result.manifest.interval).toBeNull();
    await page.getByLabel('Regression contract').selectOption('containment');
    let releaseStart: () => void = () => {};
    const pendingStart = new Promise<void>(resolve => { releaseStart = resolve; });
    await page.route('**/api/regression-runs', async route => {
      if (route.request().method() === 'POST') await pendingStart;
      await route.continue();
    });
    const secondResponse = page.waitForResponse(r => r.url().endsWith('/api/regression-runs') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Run original-attack regression' }).click();
    await expect(page.locator('[data-regression-id]')).toHaveCount(0);
    releaseStart();
    const secondRun = await (await secondResponse).json();
    await expect(page.locator('[data-regression-id]')).toHaveAttribute('data-regression-id', secondRun.id);
    await expect(page.getByRole('heading', { name: 'Regression: completed · pass' })).toBeVisible();
    const containment = await (await page.request.get(`/api/regression-runs/${secondRun.id}`)).json();
    expect(containment.manifest.arms.fixed.harmful_attempts).toBe(1);
    expect(containment.manifest.arms.fixed.harmful_dispatches).toBe(0);
    await page.reload(); await expect(page.getByRole('heading', { name: 'Regression: completed · pass' })).toBeVisible();
    expect(await page.locator('[data-regression-id]').getAttribute('data-regression-id')).toBe(secondRun.id);
    await expect(page.getByLabel('Regression contract')).toHaveValue('containment');
    await expect(page.getByLabel('Defence configuration')).toHaveValue('containment-v1');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path: path.join(artifacts, `p5-ledger-${width}.png`), fullPage: true });
    await page.locator('[data-regression-id]').screenshot({ path: path.join(artifacts, `p5-detail-${width}.png`) });
    fs.writeFileSync(path.join(artifacts, `p5-run-${width}.json`), JSON.stringify({ record: record.id, behavioural: firstRun.id, containment: secondRun.id }));
  });
}
